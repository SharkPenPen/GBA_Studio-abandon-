/* =====================================================================
 *  game.h —— 通用游戏层：帧计数 + 界面栈
 *
 *  这是"所有类型游戏都要"的那一层，和 galgame 无关：
 *    · 帧计数：做闪烁、做动画计时、做自动演示的节奏，谁都要用
 *    · 界面栈：标题 → 游戏 → 暂停，暂停完要能回到游戏；
 *      剧情里弹出选项，选完要回到剧情。用"压栈/出栈"表达最自然，
 *      比散落一堆 `s_back = 上次是谁` 清楚得多。
 *
 *  为什么单独一个模块：这一层是将来做关卡模式、RPG 模式时**直接复用**的，
 *  不该和"对话框长什么样"混在一个文件里。
 * ===================================================================== */
#ifndef GAME_H
#define GAME_H

#include <tonc.h>

/* 界面栈最多几层（标题→游戏→暂停 已经 3 层，留点余量） */
#define GAME_STACK_MAX 6

void game_init(void);           /* 入口调一次 */
void game_tick(void);           /* 每帧调一次：帧计数 +1 */
int  game_frame(void);          /* 当前帧号（从 1 开始，用来做闪烁/计时） */

/* 界面栈 */
void game_state_set(int st);    /* 直接切到某个界面（清空栈） */
void game_state_push(int st);   /* 记住当前界面，切到新的 */
int  game_state_pop(void);      /* 回到上一个界面，返回它（栈空则返回 -1）*/
int  game_state(void);          /* 当前界面 */

#endif /* GAME_H */
